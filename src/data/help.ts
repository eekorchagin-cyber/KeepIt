import type { Screen } from '../types'

export function helpForScreen(screen: Screen): { title: string; body: string } {
  switch (screen.name) {
    case 'home':
      return {
        title: 'Разделы',
        body: 'Выберите главный объект хранения. «+» вверху — добавить новый (например «Квартира в Химках»). У объектов можно менять значок и фон. Нижнее меню — сканер, поиск и ещё.',
      }
    case 'object':
      return {
        title: 'Объект хранения',
        body: 'Список помещений без значков. «+» — добавить помещение или импортировать список вещей. Кнопка «Импорт списка вещей» кладёт коробки и вещи прямо в объект. «…» — сменить рисунок значка и цвет фона или печать меток.',
      }
    case 'place':
      return {
        title: 'Место хранения',
        body: 'Показаны вложенные места и вещи непосредственно здесь. «+» — добавить место или вещь. «Импорт списка вещей» — коробки и вещи из текста. «…» — переименовать, перенести (коробку/контейнер — вместе с содержимым), удалить (если пусто) или напечатать метку. Код места — полный путь.',
      }
    case 'add-item':
      return {
        title: 'Новая вещь',
        body: 'Укажите название, режим учёта и категорию из справочника (с подкатегориями). Название можно выбрать из справочника — категория подставится сама. Для постоянных вещей единица — шт., компл. или пар; для расходника — также кг, л, м, уп. и другие.',
      }
    case 'import-list':
      return {
        title: 'Импорт списка',
        body: 'Вставьте текст из буфера или выберите файл .txt. Абзац, который начинается со слов «Короб» или «Коробка», — это коробка: первое предложение — её название, дальше вещи внутри. Другие абзацы — отдельные вещи в этом месте. Вещи разделяются точкой с пробелом, количество — после двоеточия, числом или словом: «Струбцина большая: две штуки. Уголь: один пакет.» Символы до первой буквы пропускаются. Перед записью можно поправить названия и количество.',
      }
    case 'categorize':
      return {
        title: 'Разбор категорий',
        body: 'Здесь вещи, добавленные импортом без категории. Они сгруппированы по подсказке: «Принять для всех» назначает подсказку всей группе. У каждой вещи есть кнопки «Принять», «Другая категория» и «Удалить» (для неверно распознанных строк). Отметьте несколько вещей галочками, чтобы назначить им одну категорию, режим учёта или удалить разом. Назначенные категории запоминаются и подсказываются в следующий раз.',
      }
    case 'item':
      return {
        title: 'Карточка вещи',
        body: 'В заголовке видно название и количество. Кнопка «Передать» отмечает, у кого вещь временно и с какой даты; место хранения становится местом возврата. «Вернуть» снимает отметку. Заготовки с «требует заполнения» сначала заполните.',
      }
    case 'edit-item':
      return {
        title: 'Заполнить карточку',
        body: 'Укажите название, категорию и количество (для постоянных вещей — целое число штук). После сохранения метка снимается, вещь учитывается в остатках. Место хранения смените через «Перенести».',
      }
    case 'scan':
      return {
        title: 'Сканер',
        body: 'Наведите камеру на QR места или введите полный путь / код вручную. После распознавания откроется карточка места.',
      }
    case 'search':
      return {
        title: 'Поиск',
        body: 'Ищите по названию, категории и примечанию в активном объекте хранения.',
      }
    case 'print':
      return {
        title: 'Печать меток',
        body: 'Можно создать свободные метки на лист A4 и напечатать QR. На этикетке — полный путь места.',
      }
    case 'settings':
      return {
        title: 'Настройки',
        body: 'Тема оформления, номер и дата версии, проверка обновлений. «Включить уведомления» — телефон сообщит о новой версии (на iPhone — только у программы на экране «Домой»). Данные пока хранятся только на этом устройстве.',
      }
    case 'more':
      return {
        title: 'Ещё',
        body: 'Переданные вещи, справочник категорий, печать меток и настройки. Основные разделы — на вкладке «Разделы».',
      }
    case 'categories':
      return {
        title: 'Справочник категорий',
        body: 'Добавляйте, переименовывайте и удаляйте категории и подкатегории. При переименовании вещи обновляются автоматически; удалить можно только неиспользуемые.',
      }
    case 'lent':
      return {
        title: 'Передано на время',
        body: 'Здесь все вещи, которые отмечены как временно у кого-то: адресат и дата передачи. Нажмите строку, чтобы открыть карточку и вернуть вещь.',
      }
  }
}
