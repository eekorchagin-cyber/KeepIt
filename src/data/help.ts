import type { Screen } from '../types'

export function helpForScreen(screen: Screen): { title: string; body: string } {
  switch (screen.name) {
    case 'home':
      return {
        title: 'Разделы',
        body: 'Выберите главный объект хранения. «+» вверху — добавить новый (например «Квартира в Химках»). У объектов можно менять значок и фон. Нижнее меню — сканер, поиск и ещё.',
      }
    case 'object':
      return {
        title: 'Объект хранения',
        body: 'Список помещений без значков. «+» — добавить помещение. «…» — сменить рисунок значка и цвет фона или печать меток.',
      }
    case 'place':
      return {
        title: 'Место хранения',
        body: 'Показаны вложенные места и вещи непосредственно здесь. «+» — добавить место или вещь. «…» — переименовать, перенести (коробку/контейнер — вместе с содержимым), удалить (если пусто) или напечатать метку. Код места — полный путь.',
      }
    case 'add-item':
      return {
        title: 'Новая вещь',
        body: 'Укажите название, режим учёта и категорию из справочника (с подкатегориями). Для расходника задайте количество и единицу (шт, кг, уп).',
      }
    case 'item':
      return {
        title: 'Карточка вещи',
        body: 'В заголовке видно название и количество. Кнопка «Передать» отмечает, у кого вещь временно и с какой даты; место хранения становится местом возврата. «Вернуть» снимает отметку. Заготовки с «требует заполнения» сначала заполните.',
      }
    case 'edit-item':
      return {
        title: 'Заполнить карточку',
        body: 'Укажите название, категорию и количество (для постоянных вещей — целое число штук). После сохранения метка снимается, вещь учитывается в остатках. Место хранения смените через «Перенести».',
      }
    case 'scan':
      return {
        title: 'Сканер',
        body: 'Наведите камеру на QR места или введите полный путь / код вручную. После распознавания откроется карточка места.',
      }
    case 'search':
      return {
        title: 'Поиск',
        body: 'Ищите по названию, категории и примечанию в активном объекте хранения.',
      }
    case 'print':
      return {
        title: 'Печать меток',
        body: 'Можно создать свободные метки на лист A4 и напечатать QR. На этикетке — полный путь места.',
      }
    case 'settings':
      return {
        title: 'Настройки',
        body: 'Тема оформления и сведения о версии. Данные пока хранятся только на этом устройстве.',
      }
    case 'more':
      return {
        title: 'Ещё',
        body: 'Переданные вещи, справочник категорий, печать меток и настройки. Основные разделы — на вкладке «Разделы».',
      }
    case 'categories':
      return {
        title: 'Справочник категорий',
        body: 'Добавляйте, переименовывайте и удаляйте категории и подкатегории. При переименовании вещи обновляются автоматически; удалить можно только неиспользуемые.',
      }
    case 'lent':
      return {
        title: 'Передано на время',
        body: 'Здесь все вещи, которые отмечены как временно у кого-то: адресат и дата передачи. Нажмите строку, чтобы открыть карточку и вернуть вещь.',
      }
  }
}
